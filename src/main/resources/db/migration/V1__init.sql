CREATE TABLE customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(255) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 role VARCHAR(255) NOT NULL,
 address VARCHAR(255)
);
CREATE TABLE product (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(255) NOT NULL,
 description VARCHAR(3000),
 category VARCHAR(255), type VARCHAR(255), size VARCHAR(255), color VARCHAR(255),
 price NUMERIC(12,2) NOT NULL, stock INTEGER NOT NULL, image_urls VARCHAR(4000)
);
CREATE TABLE purchases (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL REFERENCES customers(id),
 created_at TIMESTAMP(6), total NUMERIC(12,2), status VARCHAR(255),
 payment_reference VARCHAR(255), gateway_order_id VARCHAR(255) UNIQUE,
 gateway_payment_id VARCHAR(255) UNIQUE, payment_status VARCHAR(255),
 delivery_address VARCHAR(1000)
);
CREATE TABLE purchase_item (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 purchase_id BIGINT NOT NULL REFERENCES purchases(id),
 product_id BIGINT, product_name VARCHAR(255), unit_price NUMERIC(12,2), quantity INTEGER NOT NULL
);
CREATE TABLE favorite (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL REFERENCES customers(id),
 product_id BIGINT NOT NULL REFERENCES product(id),
 CONSTRAINT uk_favorite_customer_product UNIQUE(customer_id,product_id)
);
CREATE INDEX ix_purchases_customer ON purchases(customer_id);
CREATE INDEX ix_favorite_product ON favorite(product_id);
